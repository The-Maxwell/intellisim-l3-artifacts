"""EXP-H2 billing reconciliation (protocol 37 §7 step 5; live check of D25).

Input : an OpenAI usage export (Chat Completions, daily buckets) covering 2026-09-23, placed at
        results/_billing/completions_usage_<from>_<to>.csv by the author (contains account ids — keep private,
        scrub before any public bundle), plus results/exp-h2/manifest.json and the per-report token usage
        (F2: engine report.json token_usage; A: harness usage over provider-successful attempts).
Output: results/exp-h2/COST.md (+ stdout). Only numeric columns are read; no identifier is printed.

Expected under D25: billing o4-mini rows of the EXP-H2 day == recorded usage + usage of any billed failed attempt, to the token.
Usage : python harness/exph2_cost.py --csv results/_billing/<file>.csv [--day 2026-09-23]
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from exph2_common import OUT, PRICE_PER_1M as PRICE, PRIMARY, REPO, console_utf8, cost_usd  # noqa: E402

CACHED_IN = 0.275   # o4-mini cached-input list price per 1 M tokens (same basis as exph-cost.md's ≈ $0.0011 for 1 280 tokens)


def recorded() -> dict:
    tot = {"requests": 0, "input": 0, "output": 0, "reasoning": 0}
    per = {}
    for n in PRIMARY:
        f2 = json.loads((OUT / f"f2-{n}" / "report.json").read_text(encoding="utf-8"))
        t = f2["token_usage"]["total"]
        a = json.loads((OUT / f"a-{n}" / "report.json").read_text(encoding="utf-8"))
        u = a["token_usage"]["total"]
        att = json.loads((OUT / f"a-{n}" / "attempts.json").read_text(encoding="utf-8"))
        a_ok = sum(1 for x in att if x["outcome"] == "ok")
        per[n] = {"F2": (t["calls"], t["prompt_tokens"], t["completion_tokens"]),
                  "A": (a_ok, u["prompt_tokens"], u["completion_tokens"])}
        tot["requests"] += t["calls"] + a_ok
        tot["input"] += t["prompt_tokens"] + u["prompt_tokens"]
        tot["output"] += t["completion_tokens"] + u["completion_tokens"]
        tot["reasoning"] += t.get("reasoning_tokens", 0) + u.get("reasoning_tokens", 0)
    return {"total": tot, "per_report": per}


def billed(csv_path: Path, day: str) -> dict:
    out = {"requests": 0, "input": 0, "output": 0, "cached": 0, "rows": 0}
    with csv_path.open(encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if not r["model"].startswith("o4-mini") or not r["start_time_iso"].startswith(day):
                continue
            out["rows"] += 1
            out["requests"] += int(r["num_model_requests"] or 0)
            out["input"] += int(r["input_tokens"] or 0)
            out["output"] += int(r["output_tokens"] or 0)
            out["cached"] += int(r["input_cached_tokens"] or 0)
    return out


def main() -> int:
    console_utf8()
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", required=True)
    ap.add_argument("--day", default="2026-09-23")
    a = ap.parse_args()
    rec = recorded()
    bil = billed(REPO / a.csv, a.day)
    man = json.loads((OUT / "manifest.json").read_text(encoding="utf-8"))
    failed = sum(r.get("failed_attempts", 0) + r.get("suspected_hidden_failed_attempts", 0) for r in man["rows"])
    t = rec["total"]
    d = {k: bil[k] - t[k] for k in ("requests", "input", "output")}
    exported = datetime.fromtimestamp((REPO / a.csv).stat().st_mtime, timezone.utc).strftime("%Y-%m-%dT%H:%MZ")
    if d == {"requests": 0, "input": 0, "output": 0}:
        verdict = ("**Reconciles to the token** — the engine (F2) and the harness (A) record every successful call exactly "
                   "(consistent with D25)." + (f" The {failed} logged or inferred failed attempt(s) were **not billed**."
                                               if failed else ""))
    else:
        verdict = "**Does not reconcile exactly** — see the difference row; compare with the failed attempts."
    lines = ["# EXP-H2 billing reconciliation", "",
             f"> Generated by `harness/exph2_cost.py` from `{a.csv}` (o4-mini rows dated {a.day}; file written {exported}) and the recorded usage of the 20 EXP-H2 reports.", "",
             "| Source | Requests | Input tok | Output tok (incl. reasoning) | USD at list price |", "|---|---|---|---|---|",
             f"| Recorded (F2 engine + A harness, successful attempts) | {t['requests']} | {t['input']} | {t['output']} | {cost_usd('o4-mini', t['input'], t['output']):.4f} |",
             f"| Billing export | {bil['requests']} | {bil['input']} | {bil['output']} | {cost_usd('o4-mini', bil['input'], bil['output']):.4f} |",
             f"| Difference (billing − recorded) | {d['requests']} | {d['input']} | {d['output']} | {cost_usd('o4-mini', d['input'], d['output']):.4f} |", "",
             f"Logged or inferred failed attempts: {failed}. Cached input tokens billed: {bil['cached']} "
             f"(discount ≈ ${bil['cached'] * (PRICE['o4-mini'][0] - CACHED_IN) / 1e6:.4f}, ignored as in `exph-cost.md`). "
             f"Reasoning tokens recorded: {t['reasoning']}.", "", verdict]
    (OUT / "COST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

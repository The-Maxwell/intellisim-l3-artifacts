"""Append the frozen-artefact hash block (§8) and Appendix A (verbatim metadata) to protocol 37.

Idempotent: everything after the '## 8.' heading line is regenerated.
Run after both dry runs and before the pre-registration commit:
  python harness/exph2_ablate.py --dry-run && python harness/exph2_regen.py --dry-run && python harness/exph2_prereg.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from exph2_common import OUT, PRIMARY, REPO, console_utf8, load_primary  # noqa: E402

PROTO = REPO / "experiments" / "37-exph2-regeneration-ablation-protocol.md"
HEADING = "## 8. Frozen artefacts (sha256 at pre-registration)"
FILES = ["harness/exph2_common.py", "harness/exph2_ablate.py", "harness/exph2_regen.py", "harness/exph2_run.py",
         "harness/exph2_preflight.py", "harness/exph2_prereg.py", "results/exp-h-rescoring/RUBRIC-pass2.md",
         "results/exp-h2/preflight.json", "results/exp-h2/dryrun/a-hashes.json", "results/exp-h2/dryrun/f2-hashes.json"]


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    console_utf8()
    text = PROTO.read_text(encoding="utf-8")
    head = text[: text.index(HEADING) + len(HEADING)]
    lines = ["", "", "The hash block below is generated by `harness/exph2_prereg.py` from the files as they stand at commit time.", "",
             "| File | sha256 |", "|---|---|"]
    for f in FILES:
        lines.append(f"| `{f}` | `{sha(REPO / f)}` |")
    for n in PRIMARY:
        d = OUT / "dryrun" / f"a-{n}"
        for p in sorted(d.glob("req-*.json")):
            lines.append(f"| `{p.relative_to(REPO).as_posix()}` | `{sha(p)}` |")
        p = OUT / "dryrun" / f"f2-{n}" / "request.json"
        lines.append(f"| `{p.relative_to(REPO).as_posix()}` | `{sha(p)}` |")
    lines += ["", "## Appendix A. Metadata sent to the model (verbatim, from the dry-run evidence payload)", "",
              "The same model summary and run name reach the model in EXP-H, F2 and A (A additionally lacks the run data). "
              "Context messages are those of protocol 36 §1.2.", ""]
    for n in PRIMARY:
        ev = json.loads((OUT / "dryrun" / f"a-{n}" / "evidence.json").read_text(encoding="utf-8"))
        req, _ = load_primary(n)
        m, r = ev["model"], ev["run"]
        lines += [f"**Report {n}** ({req['language']}) — run `{r['Name']}` (ConfiguredSteps {r['ConfiguredSteps']}, seed {r['Seed']}, status {r['Status']}); "
                  f"model `{m['Name']}`.", "",
                  f"> Description: {m['Description']}", "",
                  f"> Context message: {req['context_message']}", ""]
    PROTO.write_text(head + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote §8 ({len(FILES)} files + dry-run bodies) and Appendix A to {PROTO.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
